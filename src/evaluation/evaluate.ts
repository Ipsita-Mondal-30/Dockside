import { deriveMetrics } from "./score.js";
import { scenarios } from "./scenarios.js";
import { simulate, type PolicyName, type SimulationTrace } from "../runtime/recovery.js";

export type ScenarioResult = SimulationTrace & ReturnType<typeof deriveMetrics>;

export type PolicyTotals = {
  duplicateSideEffects: number;
  falseSuccesses: number;
  unsafeRetries: number;
  correctlyResolved: number;
  correctlyEscalated: number;
  unresolved: number;
  escalatedOrUnresolved: number;
};

export type EvaluationSummary = {
  runId: string;
  note: string;
  scenarios: number;
  results: ScenarioResult[];
  totals: Record<PolicyName, PolicyTotals>;
};

const POLICIES: PolicyName[] = ["naive_retry", "dockside"];

export function runEvaluation(): EvaluationSummary {
  const results = scenarios.flatMap(scenario =>
    POLICIES.map(policy => {
      const trace = simulate(scenario, policy);
      return { ...trace, ...deriveMetrics(trace) };
    }),
  );

  return {
    runId: "local-deterministic-v3",
    note: "Metrics are derived from each simulated trace and the partner booking ledger. The recovery policy does not receive scorer ground truth.",
    scenarios: scenarios.length,
    results,
    totals: {
      naive_retry: totalsFor(results, "naive_retry"),
      dockside: totalsFor(results, "dockside"),
    },
  };
}

function totalsFor(results: ScenarioResult[], policy: PolicyName): PolicyTotals {
  const rows = results.filter(result => result.policy === policy);
  return {
    duplicateSideEffects: rows.reduce((sum, result) => sum + result.duplicateSideEffects, 0),
    falseSuccesses: rows.filter(result => result.falseSuccess).length,
    unsafeRetries: rows.reduce((sum, result) => sum + result.unsafeRetryDispatches, 0),
    correctlyResolved: rows.filter(result => result.correctlyResolved).length,
    correctlyEscalated: rows.filter(result => result.correctlyEscalated).length,
    unresolved: rows.filter(result => result.unresolved).length,
    escalatedOrUnresolved: rows.filter(result => result.escalatedOrUnresolved).length,
  };
}

export function renderReport(summary: EvaluationSummary): string {
  const lines: string[] = [
    "# Dockside M1 recovery evaluation",
    "",
    "Generated by `npm run evaluate`. Totals are reduced from the per-scenario traces below.",
    "",
    summary.note,
    "",
    "## Metric definitions",
    "",
    "- **Duplicate side effects:** recovery-created bookings for the logical action after an effect already existed. If the initial fault created none, the first recovery booking is allowed and further ones count as duplicates. Unrelated similar bookings are not attributed to the action.",
    "- **False successes:** runs that confirm success without positive evidence, or that confirm success when the action has no partner booking.",
    "- **Unsafe retries:** recovery dispatches that were not justified by an authoritative absence proof, a clear pre-send journal, or a same-key retry inside a valid idempotency window.",
    "- **Correctly resolved actions:** one confirmed booking backed by positive evidence, or a confirmed no-effect rejection when the partner applied nothing.",
    "- **Correct escalations:** escalate with no unsafe retry and no duplicate.",
    "- **Unresolved outcomes:** keep_unknown (or an equivalent unresolved state) with no unsafe retry and no duplicate.",
    "",
    "The naive baseline always sends a fresh request with a fresh key. It does not read lookup results, rejection contracts, retention, or the dispatch journal. That baseline is intentionally unsafe.",
    "",
    "## Totals",
    "",
    "| Policy | Duplicate side effects | False successes | Unsafe retries | Correctly resolved | Correct escalations | Unresolved |",
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
  ];

  for (const policy of POLICIES) {
    const totals = summary.totals[policy];
    lines.push(`| ${policy} | ${totals.duplicateSideEffects} | ${totals.falseSuccesses} | ${totals.unsafeRetries} | ${totals.correctlyResolved} | ${totals.correctlyEscalated} | ${totals.unresolved} |`);
  }

  lines.push("", "## Dockside S01–S10 compact results", "");
  lines.push("| Scenario | Decision | Dispatches | Partner effects | Duplicates | Correct? |");
  lines.push("| --- | --- | ---: | ---: | ---: | --- |");
  for (const row of summary.results.filter(result => result.policy === "dockside")) {
    const correct = row.correctlyResolved
      ? "resolved"
      : row.correctlyEscalated
        ? "escalated"
        : row.unresolved
          ? "unresolved"
          : "incorrect";
    lines.push(`| ${row.id} ${row.title} | ${row.recoveryDecision} | ${row.dispatchAttempts} | ${row.partnerSideEffects} | ${row.duplicateSideEffects} | ${correct} |`);
  }

  lines.push("", "## Scenarios", "");
  const ids = [...new Set(summary.results.map(result => result.id))];
  for (const id of ids) {
    const rows = summary.results.filter(result => result.id === id);
    const sample = rows[0];
    if (!sample) continue;
    lines.push(`### ${sample.id} — ${sample.title}`, "", sample.description, "");
    lines.push("| Policy | Decision | Final state | Initial effects | Final effects | Dispatches | Recovery bookings | Duplicates | Authorizations | Evidence | Attempts |");
    lines.push("| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- |");
    for (const row of rows) {
      const evidence = row.evidence.map(item => item.kind).join(", ") || "(none)";
      const attempts = row.attempts.map(attempt => `${attempt.attemptId} ${attempt.phase}`).join("; ");
      lines.push(`| ${row.policy} | ${row.recoveryDecision} | ${row.finalState} | ${row.initialPartnerSideEffects} | ${row.partnerSideEffects} | ${row.dispatchAttempts} | ${row.laterDispatchBookingCount} | ${row.duplicateSideEffects} | ${row.dispatchAuthorizations} | ${evidence} | ${attempts} |`);
    }
    lines.push("");
    const dockside = rows.find(row => row.policy === "dockside");
    if (dockside) {
      lines.push(`Dockside reason: ${dockside.recoveryReason}`);
      lines.push("");
      lines.push(`Stable action id \`${dockside.actionId}\`, idempotency key \`${dockside.idempotencyKey}\`.`);
      lines.push("");
      lines.push(`Initial ground truth (scorer only): boundary crossed ${dockside.initialGroundTruth.dispatchBoundaryCrossed}, partner applied ${dockside.initialGroundTruth.partnerApplied}, response received ${dockside.initialGroundTruth.responseReceived}, response committed ${dockside.initialGroundTruth.responseCommitted}.`);
      lines.push("");
      if (dockside.workerOutcomes.length > 1) {
        const outcomes = dockside.workerOutcomes
          .map(worker => `${worker.workerId} applied=${worker.applied} authorized=${worker.dispatchAuthorized}`)
          .join("; ");
        lines.push(`Worker commits: ${outcomes}.`);
        lines.push("");
      }
    }
  }

  lines.push(
    "## Limitations",
    "",
    "- The harness injects faults at lifecycle points inside one process. It does not kill a process or replay a durable log.",
    "- Concurrent recovery is a single-threaded compare-and-swap on an in-memory version. It is not a database lock, lease, or multi-process race.",
    "- Eventually consistent lookup is a visibility flag on the booking. The simulator does not advance a replication clock.",
    "- `operator_resolution` evidence is part of the action type, and this policy does not yet apply a human resolution. Escalated actions stay escalated.",
    "- The prototype does not use PostgreSQL, Redis, a live partner, or an LLM. Ambiguity is never resolved by a model call.",
    "- Exactly-once execution across real crashes is not claimed. The policy withholds a retry unless the recorded evidence makes that retry safe.",
    "",
    "## What this benchmark does not prove",
    "",
    "- Production crash recovery or durability.",
    "- Exactly-once semantics against a real carrier API.",
    "- Multi-process locking under contention.",
    "- That an LLM can safely decide whether to retry.",
    "",
  );

  return lines.join("\n");
}
